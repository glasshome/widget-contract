import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { compileMessage, parseCatalog } from "./i18n";
import type { BundledCatalog, CompiledCatalog, MessagePart } from "./i18n-format";

const ACCENTS: Readonly<Record<string, string>> = {
  a: "á",
  e: "é",
  i: "í",
  o: "ó",
  u: "ú",
  c: "ç",
  n: "ñ",
  A: "Á",
  E: "É",
  I: "Í",
  O: "Ó",
  U: "Ú",
  C: "Ç",
  N: "Ñ",
};

export function compileCatalogSource(text: string, origin: string): CompiledCatalog {
  const parsed = parseCatalog(text);
  if (!parsed.ok) {
    const error = parsed.error;
    const key = "key" in error ? `${error.key}: ` : "";
    const reason = "reason" in error ? error.reason : error.kind;
    throw new Error(`${origin}: ${key}${reason}`);
  }
  const out: Record<string, readonly MessagePart[]> = {};
  for (const [key, source] of parsed.value) {
    const compiled = compileMessage(source);
    if (!compiled.ok) throw new Error(`${origin}: ${key}: ${compiled.error}`);
    out[key] = compiled.value;
  }
  return out;
}

function accent(text: string): string {
  return text.replace(/[aeioucnAEIOUCN]/g, (letter) => ACCENTS[letter] ?? letter);
}

function literalLength(parts: readonly MessagePart[]): number {
  let total = 0;
  for (const part of parts) {
    if (typeof part === "string") total += part.length;
    else if ("branches" in part) {
      for (const branch of Object.values(part.branches)) total += literalLength(branch);
    }
  }
  return total;
}

function accentParts(parts: readonly MessagePart[]): MessagePart[] {
  return parts.map((part): MessagePart => {
    if (typeof part === "string") return accent(part);
    if ("branches" in part) {
      const branches: Record<string, readonly MessagePart[]> = {};
      for (const [name, branch] of Object.entries(part.branches))
        branches[name] = accentParts(branch);
      return "plural" in part
        ? { plural: part.plural, branches }
        : { select: part.select, branches };
    }
    return part;
  });
}

function bracket(parts: MessagePart[], tail: string): MessagePart[] {
  const out: MessagePart[] = ["[", ...parts, tail];
  return out.reduce<MessagePart[]>((merged, part) => {
    const prev = merged[merged.length - 1];
    if (typeof part === "string" && typeof prev === "string")
      merged[merged.length - 1] = prev + part;
    else merged.push(part);
    return merged;
  }, []);
}

export function pseudoCatalog(en: CompiledCatalog): CompiledCatalog {
  const out: Record<string, readonly MessagePart[]> = {};
  for (const [key, message] of Object.entries(en)) {
    const padding = "~".repeat(Math.ceil(0.4 * literalLength(message)));
    out[key] = bracket(accentParts(message), ` ${padding}]`);
  }
  return out;
}

export function catalogModule(catalog: CompiledCatalog): string {
  return `export default ${JSON.stringify(catalog)};\n`;
}

export function bundledCatalogModule(catalog: CompiledCatalog): string {
  const bundled: BundledCatalog = { v: 1, messages: catalog };
  return `export default ${JSON.stringify(bundled)};\n`;
}

const PSEUDO = "en-XA";
const SOURCE = /^([a-z]{2})\.json$/u;

function compiledModule(language: string, catalog: CompiledCatalog, keyType: string): string {
  const body = JSON.stringify(catalog, null, 2);
  const origin = language === PSEUDO ? "en" : language;
  const head = `// Generated by \`bun run catalogs\` from ${origin}.json; do not edit.\nimport type { CompiledCatalog } from "@glasshome/widget-contract/i18n-format";\n\n`;
  return language === "en"
    ? `${head}const catalog = ${body} satisfies CompiledCatalog;\n\nexport type ${keyType} = keyof typeof catalog;\nexport default catalog;\n`
    : `${head}const catalog: CompiledCatalog = ${body};\n\nexport default catalog;\n`;
}

/** Every `<lang>.json` in `localesDir` compiled, plus the `en-XA` pseudo catalog made from English. */
export function compileCatalogDir(localesDir: string): Record<string, CompiledCatalog> {
  const catalogs: Record<string, CompiledCatalog> = {};
  for (const name of readdirSync(localesDir).sort()) {
    const language = SOURCE.exec(name)?.[1];
    if (!language) continue;
    const file = join(localesDir, name);
    catalogs[language] = compileCatalogSource(readFileSync(file, "utf-8"), file);
  }
  const en = catalogs.en;
  if (!en) throw new Error(`${localesDir}: no en.json`);
  return { ...catalogs, [PSEUDO]: pseudoCatalog(en) };
}

/**
 * Writes `compileCatalogDir(localesDir)` to `<localesDir>/compiled/<lang>.ts` and returns the
 * files. `keyType` names the exported key union of the English module.
 */
export function writeCatalogModules(localesDir: string, keyType: string): string[] {
  const catalogs = compileCatalogDir(localesDir);
  const out = join(localesDir, "compiled");
  mkdirSync(out, { recursive: true });
  return Object.entries(catalogs).map(([language, catalog]) => {
    const file = join(out, `${language}.ts`);
    writeFileSync(file, compiledModule(language, catalog, keyType));
    return file;
  });
}
